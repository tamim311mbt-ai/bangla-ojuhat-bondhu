// ==================== sessionStorage জিরো-রিপিটেশন ট্র্যাকার ====================

const SEEN_STORAGE_KEY = "ojuhat-seen-excuses-v1";
const MAX_SEEN_ENTRIES = 2000;
const memorySeenFallback = new Set<string>();

function getSessionStorageSafe(): Storage | null {
  try {
    if (typeof window !== "undefined" && window.sessionStorage) {
      return window.sessionStorage;
    }
  } catch {
    // Restricted privacy context
  }
  return null;
}

function readSeenList(): string[] {
  const storage = getSessionStorageSafe();
  if (!storage) {
    return Array.from(memorySeenFallback);
  }
  try {
    const raw = storage.getItem(SEEN_STORAGE_KEY);
    if (!raw) return Array.from(memorySeenFallback);
    const parsed = JSON.parse(raw) as unknown;
    if (Array.isArray(parsed)) {
      return parsed.filter((item): item is string => typeof item === "string");
    }
  } catch {
    // Ignore malformed sessionStorage payload
  }
  return Array.from(memorySeenFallback);
}

function writeSeenList(list: string[]): void {
  const trimmed = list.slice(-MAX_SEEN_ENTRIES);
  memorySeenFallback.clear();
  for (const item of trimmed) {
    memorySeenFallback.add(item);
  }
  const storage = getSessionStorageSafe();
  if (!storage) return;
  try {
    storage.setItem(SEEN_STORAGE_KEY, JSON.stringify(trimmed));
  } catch {
    // Ignore sessionStorage quota or privacy errors
  }
}

export function normalizeExcuseKey(text: string): string {
  return text.trim().replace(/\s+/g, " ");
}

export function hasExcuseBeenSeen(identifier: string): boolean {
  const normalized = normalizeExcuseKey(identifier);
  if (!normalized) return false;
  const list = readSeenList();
  return list.includes(normalized);
}

export function markExcuseAsSeen(identifier: string): void {
  const normalized = normalizeExcuseKey(identifier);
  if (!normalized) return;
  const list = readSeenList();
  if (list.includes(normalized)) return;
  list.push(normalized);
  writeSeenList(list);
}

export function getSeenExcuseCount(): number {
  return readSeenList().length;
}

export function clearSeenExcuses(): void {
  memorySeenFallback.clear();
  const storage = getSessionStorageSafe();
  if (!storage) return;
  try {
    storage.removeItem(SEEN_STORAGE_KEY);
  } catch {
    // Ignore
  }
}

// ==================== পুল ও কম্বিনেটর জেনারেটর ====================

export function isAllowed(e: Excuse, target: Target): boolean {
  if (e.only && !e.only.includes(target)) return false;
  if (e.except && e.except.includes(target)) return false;
  return true;
}

export function getPool(target: Target, problem: Problem, tone: Tone): Excuse[] {
  return BASE_EXCUSES.filter(
    (e) => e.problem === problem && e.tone === tone && isAllowed(e, target),
  );
}

export interface CombinatorResult {
  variationId: string;
  text: string;
  score: number;
}

export function getCombinatorVariationCountForCategory(
  target: Target,
  problem: Problem,
  tone: Tone,
): number {
  const openings = COMBINATOR_OPENINGS[target][tone].length;
  const cores = COMBINATOR_CORES[problem][tone].length;
  const closings = COMBINATOR_CLOSINGS[target][tone].length;
  return openings * cores * closings;
}

export function getTotalUniqueVariationCount(): number {
  let combinatorTotal = 0;
  for (const t of TARGETS) {
    for (const p of PROBLEMS) {
      for (const tone of TONES) {
        combinatorTotal += getCombinatorVariationCountForCategory(t.value, p.value, tone.value);
      }
    }
  }
  return BASE_EXCUSES.length + combinatorTotal;
}

function defaultScoreForTone(tone: Tone): number {
  return tone === "funny" ? 18 : tone === "emotional" ? 73 : 85;
}

export function buildCombinatorVariation(
  target: Target,
  problem: Problem,
  tone: Tone,
  openingIdx: number,
  coreIdx: number,
  closingIdx: number,
  customText?: string | undefined,
): CombinatorResult {
  const openings = COMBINATOR_OPENINGS[target][tone];
  const cores = COMBINATOR_CORES[problem][tone];
  const closings = COMBINATOR_CLOSINGS[target][tone];

  const o = openings[openingIdx % openings.length] ?? openings[0] ?? "";
  const c = cores[coreIdx % cores.length] ?? cores[0] ?? "";
  const cl = closings[closingIdx % closings.length] ?? closings[0] ?? "";

  const cleanCustom = customText?.trim().replace(/[।.!?]+$/, "");
  const middle = cleanCustom
    ? tone === "funny"
      ? `"${cleanCustom}" নিয়ে যে কী বিপদে পড়েছি বলার মতো না—${c}`
      : tone === "emotional"
        ? `"${cleanCustom}" ব্যাপারটা নিয়ে সত্যিই ভীষণ চাপের মধ্যে আছি। ${c}`
        : `"${cleanCustom}" এর কারণেই এই ঝামেলায় আটকে গেছি—${c}`
    : c;

  return {
    variationId: `combo-${target}-${problem}-${tone}-${openingIdx}-${coreIdx}-${closingIdx}`,
    text: `${o} ${middle} ${cl}`.replace(/\s+/g, " ").trim(),
    score: defaultScoreForTone(tone),
  };
}

export function pickUnseenCombinatorVariation(
  target: Target,
  problem: Problem,
  tone: Tone,
  rand: () => number = Math.random,
  customText?: string | undefined,
  previousMessage?: string | undefined,
): CombinatorResult {
  const openings = COMBINATOR_OPENINGS[target][tone];
  const cores = COMBINATOR_CORES[problem][tone];
  const closings = COMBINATOR_CLOSINGS[target][tone];
  const total = openings.length * cores.length * closings.length;

  const startIndex = Math.floor(rand() * total);
  for (let offset = 0; offset < total; offset++) {
    const idx = (startIndex + offset) % total;
    const oIdx = Math.floor(idx / (cores.length * closings.length)) % openings.length;
    const cIdx = Math.floor(idx / closings.length) % cores.length;
    const clIdx = idx % closings.length;

    const candidate = buildCombinatorVariation(
      target,
      problem,
      tone,
      oIdx,
      cIdx,
      clIdx,
      customText,
    );
    if (
      candidate.text !== previousMessage &&
      !hasExcuseBeenSeen(candidate.variationId) &&
      !hasExcuseBeenSeen(candidate.text)
    ) {
      return candidate;
    }
  }

  // Fallback if all combinations in this bucket were seen during one massive session
  const oIdx = Math.floor(rand() * openings.length);
  const cIdx = Math.floor(rand() * cores.length);
  const clIdx = Math.floor(rand() * closings.length);
  return buildCombinatorVariation(target, problem, tone, oIdx, cIdx, clIdx, customText);
}
