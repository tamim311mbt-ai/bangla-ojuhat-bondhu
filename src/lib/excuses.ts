export function isAllowed(e: Excuse, target: Target) {
  if (e.only && !e.only.includes(target)) return false;
  if (e.except && e.except.includes(target)) return false;
  return true;
}

export function getPool(target: Target, problem: Problem, tone: Tone) {
  return EXCUSES.filter((e) => e.problem === problem && e.tone === tone && isAllowed(e, target));
}

export interface GeneratedExcuse {
  id: string;
  message: string;
  score: number;
  tip: string;
}

function pick<T>(arr: T[], rand: () => number): T {
  return arr[Math.floor(rand() * arr.length)] as T;
}

export function generateExcuse(
  input: { target: Target; problem: Problem; tone: Tone; extra?: string | undefined; previousId?: string | undefined },
  rand: () => number = Math.random,
): GeneratedExcuse {
  const pool = getPool(input.target, input.problem, input.tone);
  const fresh = pool.filter((e) => e.id !== input.previousId);
  const excuse = pick(fresh.length ? fresh : pool, rand);

  const extra = input.extra?.trim().replace(/[।.!?]+$/, "");
  const parts = [`${ADDRESS[input.target]}, ${excuse.text}`];
  if (extra) parts.push(`আরেকটা কথা—${extra}।`);
  parts.push(CLOSING[input.target][input.tone]);

  const jitter = Math.round(rand() * 8) - 4;
  const score = Math.max(1, Math.min(99, excuse.score + jitter + (extra ? 3 : 0)));
  const tip = pick([...TONE_TIPS[input.tone], ...TARGET_TIPS[input.target]], rand);

  return { id: excuse.id, message: parts.join(" "), score, tip };
}

export function excuseOfTheDay(date: Date = new Date()): Excuse {
  const start = Date.UTC(date.getFullYear(), 0, 0);
  const day = Math.floor((Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) - start) / 86400000);
  const general = EXCUSES.filter((e) => !e.only);
  return general[(day * 7 + date.getFullYear()) % general.length] as Excuse;
}

